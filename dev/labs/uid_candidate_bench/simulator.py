"""Loopback-only, synthetic stock U1 subset; optional synthetic RFID, no printer writes."""
import asyncio,time,sys,json
from pathlib import Path
from aiohttp import web
port=int(sys.argv[1])
stats=dict(state='standby',filename='',filament_used=0)
jobs=[]; clients=set()
faults={'remaining':0,'used':0}
feed=dict(module_exist=True,disable_auto=False,filament_detected=True)
status=dict(print_stats=stats,webhooks=dict(state='ready'),print_task_config=dict(auto_replenish_filament=False,extruder_map_table=list(range(4)),extruders_replenished=list(range(4))),
    filament_detect={'state':[0]*4,'info':[{'CARD_UID':0}]*4},toolhead={'extruder':'extruder'})
for side,ids in [('left',(0,1)),('right',(2,3))]:status['filament_feed '+side]={f'extruder{i}':feed for i in ids}
gcode=b'; generated by OrcaSlicer 2.3.0\n; filament used [g] = 18.42,0,0,0\n; filament_density = 1.24,1.24,1.24,1.24\n; filament_diameter = 1.75,1.75,1.75,1.75\n; filament_type = PLA;PLA;PLA;PLA\nG1 X1\n'
if '--reader' in sys.argv:
    status['tracker_uid']=dict(schema_version=1,epoch='sim-1',sequence=0,state='ready',
        channels={str(i):dict(state='absent',uid=None) for i in range(4)})
async def handler(r):
    if '--reader-status-file' in sys.argv:
        source=Path(sys.argv[sys.argv.index('--reader-status-file')+1])
        status['tracker_uid']=json.loads(source.read_text())
    path=r.path
    if path in ('/websocket','/klippysocket'):
        ws=web.WebSocketResponse();await ws.prepare(r)
        try:
            async for message in ws:
                q=message.json();m=q['method']
                value={'status':status,'eventtime':time.monotonic()}
                if m=='printer.objects.list':value={'objects':list(status)}
                if m=='motion_report/dump_trapq':
                    value={'header':['time','duration','velocity','acceleration','position','direction']}
                    if q['id']==4:clients.add(ws)
                await ws.send_json(dict(id=q['id'],result=value))
        finally:clients.discard(ws)
        return ws
    if path=='/event':
        a=await r.json(); action=a['action'];method='notify_tracker_status'
        if action=='telemetry':
            stats.update(state=a['state'],filename=a.get('filename','dashboard-bench.gcode'))
            for key in ('print_duration','info'):stats.pop(key,None)
            if a.get('known',True):
                stats.update(print_duration=11880,info=dict(current_layer=142,total_layer=230))
                status['display_status']={'progress':.62}
            else:status.pop('display_status',None)
            status['toolhead']={'extruder':'extruder1'}
            return web.json_response({'result':True})
        if action=='tag':
            reader=status['tracker_uid'];reader['sequence']+=1
            tag=a.get('tag')
            reader['channels']['0']=dict(state='present',uid=tag['uid'],tag=tag,sequence=reader['sequence'],age_seconds=0) if tag else dict(state='absent',uid=None)
            return web.json_response({'result':True})
        if action=='history_timeout':
            faults['remaining']=1
            return web.json_response({'result':True})
        if action=='start':
            stats.update(state='printing',filename=a['filename'],filament_used=0)
            jobs.insert(0,dict(job_id=str(len(jobs)+1),status='in_progress',start_time=time.time(),filename=a['filename'],filament_used=0))
        if action=='motion':
            stats['filament_used']+=a['length'];method='notify_tracker_head_0'
        if action=='complete':
            stats['state']='complete';jobs[0].update(status='completed',end_time=time.time(),filament_used=stats['filament_used'])
        msg=dict(status={'print_stats':stats},eventtime=time.monotonic()) if action!='motion' else dict(data=[[a['stamp'],1,a['length'],0,[0,0,0],[1,0,0]]])
        for ws in list(clients):await ws.send_json(dict(method=method,params=msg))
        v=True
    elif path=='/server/files/metadata':v={'size':len(gcode),'modified':1000,'filament_type':'PLA'}
    elif path.startswith('/server/files/gcodes/'):return web.Response(body=gcode)
    elif path=='/server/history/list':
        if faults['remaining']:
            faults['remaining']-=1;faults['used']+=1
            await asyncio.sleep(3.2)
        v={'jobs':jobs,'count':len(jobs)}
    elif path=='/printer/objects/list':v={'objects':list(status)}
    elif path=='/printer/objects/query':v={'status':status}
    elif path=='/ready':v=dict(motion_clients=len(clients),faults_used=faults['used'])
    else:return web.Response(status=404)
    return web.json_response({'result':v})
app=web.Application();app.router.add_route('*','/{tail:.*}',handler)
web.run_app(app,host='127.0.0.1',port=port,print=None)
