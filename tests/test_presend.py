@pytest.mark.parametrize('target', ['gcode', 'inventory', 'response'])
def test_changed_input_or_unrelated_permission_never_sends(request_data, tmp_path, target):
    # Real evaluator succeeds; modify original inputs or response before returning allow.
    repo = str(Path(__file__).resolve().parents[1] / 'src')
    mutation = {
        'gcode': f"Path({request_data['gcode_path']!r}).write_text('changed')",
        'inventory': f"Path({request_data['inventory_path']!r}).write_text('{{}}')",
        'response': "result['request_fingerprint'] = 'another-request'",
    }[target]
    checker = tmp_path / 'mutating_checker.py'
    checker.write_text(f'import sys,json\nfrom pathlib import Path\nsys.path.insert(0,{repo!r})\n'
                       'from presend import evaluate\n'
                       'result=evaluate(json.loads(Path(sys.argv[2]).read_text()))\n'
                       + mutation + '\nprint(json.dumps(result))\n')
    adapter = TestAdapter()
    assert_blocked(adapter, adapter.execute(request_data, checker_command=[sys.executable, str(checker)]))


def test_mapping_aggregates_demand(request_data):
    request_data['mapping'] = [0, 0, 2, 3]
    rewrite_db(request_data, lambda db: db['spools']['s1'].update(remaining_g=34))
    response = evaluate(request_data)
    assert response['decision'] == 'deny'
    assert response['rows'][0]['required_g'] == 30
    rewrite_db(request_data, lambda db: db['spools']['s1'].update(remaining_g=35))
    assert evaluate(request_data)['decision'] == 'allow'


