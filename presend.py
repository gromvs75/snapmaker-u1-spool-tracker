"""v1.2-alpha strict, read-only pre-send CLI. No UI, network or default store.

Run: python presend.py --request request.json
Exit 0: explicit allow; 23: policy denial; 24: invalid input/internal error.
Only the documented four-logical-material alpha format is supported.
"""
import argparse
import hashlib
import json
import math
import re
import sys
from pathlib import Path

from gcode import METADATA, _parse_line
from material_guard import compare_materials
from preflight import check, has_problem
from tool_mapping import physical_weights, validate_mapping

VERSION = 1


def digest(data):
    return hashlib.sha256(data).hexdigest()


def _pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError('Duplicate JSON key')
        result[key] = value
    return result


def decode_json(data):
    def invalid(value):
        raise ValueError('Non-finite JSON value')
    return json.loads(data, object_pairs_hook=_pairs, parse_constant=invalid)


def fingerprint(value):
    return digest(json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False).encode())


def validate_request(request):
    if not isinstance(request, dict) or type(request.get('version')) is not int or request['version'] != VERSION:
        raise ValueError('Unsupported request version')
    for key in ('request_id', 'device_id', 'context_id', 'gcode_path', 'inventory_path'):
        if not isinstance(request.get(key), str) or not request[key].strip():
            raise ValueError('Missing ' + key)
    if request.get('action') not in ('send', 'print'):
        raise ValueError('Unsupported action')
    if not isinstance(request.get('sha256'), str) or not re.fullmatch('[0-9a-f]{64}', request['sha256']):
        raise ValueError('Invalid G-code hash')
    mapping = request.get('mapping')
    if not isinstance(mapping, list) or len(mapping) != 4:
        raise ValueError('Alpha requires exactly four logical mapping entries')
    validate_mapping(mapping)


def validate_inventory(db):
    if not isinstance(db, dict) or not isinstance(db.get('slots'), dict) or not isinstance(db.get('spools'), dict):
        raise ValueError('Invalid inventory')
    def number(value):
        return type(value) in (int, float) and math.isfinite(value) and value >= 0
    if not number(db.get('safety_margin_g')):
        raise ValueError('Invalid reserve')
    for key in ('1', '2', '3', '4'):
        if not isinstance(db['slots'].get(key), str):
            raise ValueError('Missing slot')
    for spool_id, spool in db['spools'].items():
        if not spool_id or not isinstance(spool, dict) or not isinstance(spool.get('name'), str) or not number(spool.get('remaining_g')):
            raise ValueError('Invalid spool')
    assigned = [v for v in db['slots'].values() if v]
    if len(assigned) != len(set(assigned)):
        raise ValueError('One spool cannot be assigned to multiple heads in alpha')


def metadata(data):
    """Conservative alpha parser: unique, explicit four-channel metadata only."""
    lines = data.decode('utf-8').splitlines()
    if not any(re.match(r'^;\s*generated by Snapmaker\s*Orca\b', line, re.I) for line in lines):
        raise ValueError('Unsupported or unidentified slicer')
    usage = [line for line in lines if METADATA.match(line)]
    types = [m.group(1) for line in lines
             if (m := re.match(r'^;\s*filament_type\s*=\s*(.*?)\s*$', line))]
    if len(usage) != 1 or len(types) != 1:
        raise ValueError('Missing or ambiguous material metadata')
    if len(METADATA.match(usage[0]).group(1).split(',')) != 4:
        raise ValueError('Alpha requires four explicit weights')
    weights = _parse_line(usage[0])
    if len(types[0].split(';')) != 4 or not any(weights):
        raise ValueError('Unsupported material channels or empty job')
    # Explicit tool selections outside the supported range must never be ignored.
    for line in lines:
        command = line.split(';', 1)[0].strip()
        if re.match(r'^T\d', command) and not re.fullmatch(r'T[0-3]', command):
            raise ValueError('Unsupported tool selection')
    return weights, {'slicer': 'SnapmakerOrca', 'filament_type': types[0], 'filament_weight': weights}


def evaluate(request):
    """Read explicit paths once; never persist a plan or debit inventory."""
    validate_request(request)
    data = Path(request['gcode_path']).read_bytes()
    inventory_bytes = Path(request['inventory_path']).read_bytes()
    if digest(data) != request['sha256']:
        raise ValueError('G-code changed')
    db = decode_json(inventory_bytes)
    validate_inventory(db)
    weights, meta = metadata(data)
    physical = physical_weights(weights, request['mapping'])
    rows = check(physical, db)
    materials = compare_materials(meta, weights, request['mapping'], db)
    allowed = not has_problem(rows) and all(r['status'] in ('unused', 'match') for r in materials)
    return {'version': VERSION, 'decision': 'allow' if allowed else 'deny',
            'request_fingerprint': fingerprint(request), 'sha256': digest(data),
            'inventory_sha256': digest(inventory_bytes), 'rows': rows, 'materials': materials,
            'reason': 'checked' if allowed else 'Insufficient/unassigned spool or unknown/mismatched material'}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--request', required=True, type=Path)
    args = parser.parse_args(argv)
    try:
        response = evaluate(decode_json(args.request.read_bytes()))
        code = 0 if response['decision'] == 'allow' else 23
    except Exception as exc:
        response = {'version': VERSION, 'decision': 'error', 'reason': str(exc)}
        code = 24
    print(json.dumps(response, allow_nan=False))
    return code


if __name__ == '__main__':
    sys.exit(main())
