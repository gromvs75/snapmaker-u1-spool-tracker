"""Isolated complete Tracker dashboard + loopback mock. No tray/monitor."""
import json
from pathlib import Path
import tempfile
import threading
from http.server import ThreadingHTTPServer

from dev.mock_sender_u1 import MockSenderU1
from sender_dashboard import SenderDashboard
from storage import Store
import spool_tracker


class Demo:
    def __init__(self, directory, fault='', timeout=2, http_port=0, ws_port=0):
        self.root = Path(directory)
        self.store = Store(self.root / 'inventory', legacy_paths=())
        def seed(db):
            db['language'] = 'ru'
            db['safety_margin_g'] = 5
            db['spools'] = {f's{i}': {'name':f'Тестовая PLA {i+1}', 'material':'PLA','remaining_g':100} for i in range(4)}
            db['slots'] = {str(i+1):f's{i}' for i in range(4)}
        if not self.store.path.exists():
            self.store.update(seed)
        self.mock = MockSenderU1(fault, http_port=http_port, ws_port=ws_port)
        self.controller = SenderDashboard(self.root / 'sender', self.store.path, self.mock.http_url, self.mock.ws_url, timeout)
        class Handler(spool_tracker.WebHandler):
            # Even a manually crafted request must not reach the printer APIs.
            def do_GET(self):
                if self.path not in ('/', '/index.html', '/api/data', '/api/statistics', '/api/sender/status'):
                    return self._response(403, {'error': 'Isolated sender demo only'})
                return super().do_GET()

            def do_POST(self):
                if not self.path.startswith('/api/sender/'):
                    return self._response(403, {'error': 'Isolated sender demo only'})
                return super().do_POST()
        Handler.store = self.store
        Handler.sender_controller = self.controller
        self.server = ThreadingHTTPServer(('127.0.0.1',0), Handler)
        # Same host/origin guards as the actual dashboard, without fixed port collision.
        port = self.server.server_port
        Handler._allowed_host = lambda handler: handler.headers.get('Host') in (f'127.0.0.1:{port}',f'localhost:{port}')
        spool_tracker.WEB_PORT = port
        self.url = f'http://127.0.0.1:{port}'
        self.fixture = self.root / 'test-cube.gcode'
        self.fixture.write_text('; generated by Snapmaker Orca 2.4.1\n; filament_type = PLA;PLA;PLA;PLA\n; filament used [g] = 10, 20, 0, 0\nT0\n')

    def __enter__(self):
        self.mock.__enter__()
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()
        return self

    def __exit__(self,*args):
        self.server.shutdown(); self.server.server_close(); self.thread.join(timeout=2)
        self.mock.__exit__(*args)


def main():
    directory = tempfile.mkdtemp(prefix='tracker-ui-demo-')
    with Demo(directory) as demo:
        print(json.dumps({'url':demo.url, 'fixture':str(demo.fixture), 'directory':directory}), flush=True)
        try:
            threading.Event().wait()
        except KeyboardInterrupt:
            return 0


if __name__ == '__main__':
    main()
