@pytest.mark.parametrize('action', ['send','print'])
@pytest.mark.parametrize('fault', ['allow','deny','crash','timeout','bad_json','wrong_mapping','no_offline'])
def test_cpp_to_strict_checker(bridge, stand, tmp_path, action, fault):
    source, inventory, config, context, report, env = stand
    before = inventory.read_bytes()
    if fault == 'deny':
        data = json.loads(before)
        data['spools']['spool']['remaining_g'] = 0
        inventory.write_text(json.dumps(data))
    elif fault in ('crash','timeout','bad_json'):
        checker = tmp_path / 'fault.py'
        checker.write_text({'crash':'raise RuntimeError("fault")',
                            'timeout':'import time; time.sleep(10)',
                            'bad_json':'print("not json")'}[fault])
        config['checker_command'] = [sys.executable, str(checker)]
    elif fault == 'wrong_mapping':
        config['mapping'] = [0,1,2,3,0]
    elif fault == 'no_offline':
        config['offline_test'] = False
    context.write_text(json.dumps(config))
    before = inventory.read_bytes()
    run = subprocess.run([str(bridge), str(source), 'cube.gcode', action, '3000'],
                         env=env, capture_output=True, timeout=5)
    result = json.loads(report.read_text())
    assert inventory.read_bytes() == before
    if fault == 'allow':
        assert run.returncode == 0
        assert len(result['uploads']) == 1
        assert len(result['starts']) == (1 if action == 'print' else 0)
    else:
        assert run.returncode == 23
        assert result['uploads'] == result['starts'] == []
        if fault == 'timeout':
            assert 'timed out' in result['result']['reason']


@pytest.mark.parametrize('fault', ['missing_env', 'missing_runner', 'hanging_runner', 'false_success', 'overflow'])
def test_cpp_bridge_itself_fails_closed(bridge, stand, tmp_path, fault):
    source, inventory, config, context, report, env = stand
    if fault == 'missing_env':
        del env['TRACKER_U1_TEST_CONTEXT']
    elif fault == 'missing_runner':
        env['TRACKER_U1_TEST_RUNNER'] = str(tmp_path / 'absent.py')
    else:
        runner = tmp_path / 'runner.py'
        runner.write_text({'hanging_runner':'import time; time.sleep(10)',
                           'false_success':'print("allow")',
                           'overflow':'print("x"*10000)'}[fault])
        env['TRACKER_U1_TEST_RUNNER'] = str(runner)
    run = subprocess.run([str(bridge),str(source),'cube.gcode','print','200'],
                         env=env, capture_output=True, timeout=3)
    assert run.returncode == 23
    assert not report.exists()  # offline transport endpoint was not reached


def test_paths_and_display_are_not_shell_commands(bridge, stand, tmp_path):
    source, inventory, config, context, report, env = stand
    marker = tmp_path / 'MUST_NOT_EXIST'
    display = 'cube; touch ' + str(marker) + '; $(false).gcode'
    config['checker_timeout'] = 2
    context.write_text(json.dumps(config))
    run = subprocess.run([str(bridge),str(source),display,'send','3000'],env=env,timeout=5)
    assert run.returncode == 0
    assert not marker.exists()
    assert json.loads(report.read_text())['display'] == display


def test_patch_applies_to_pinned_source_and_returns_before_gateway(tmp_path):
    upstream_path = os.environ.get('TRACKER_TEST_PLATER_SOURCE')
    if not upstream_path:
        pytest.skip('Set TRACKER_TEST_PLATER_SOURCE to the pinned upstream Plater.cpp')
    original = Path(upstream_path).read_bytes()
    pin = json.loads((INTEGRATION / 'source_pin.json').read_text())
    assert hashlib.sha256(original).hexdigest() == pin['sha256']
    destination = tmp_path / 'src/slic3r/GUI/Plater.cpp'
    destination.parent.mkdir(parents=True)
    destination.write_bytes(original)
    patch = str(INTEGRATION / 'snorca.patch')
    subprocess.run(['git','apply','--check',patch],cwd=tmp_path,check=True)
    subprocess.run(['git','apply',patch],cwd=tmp_path,check=True)
    result = destination.read_text()
    assert (destination.parent / 'TrackerU1Offline.hpp').read_bytes() == (INTEGRATION / 'TrackerU1Offline.hpp').read_bytes()
    branch = result[result.index('// Tracker v1.2-alpha:'):]
    assert branch.index('return;') < branch.index('gateway_store_preprint_context')
    assert branch.index('return;') < branch.index('config->set_bool')
    assert branch.index('return;') < branch.index('new WebPreprintDialog')


def test_os_isolation_is_enforced():
    if os.environ.get('TRACKER_ASSERT_OS_ISOLATION') != '1':
        pytest.skip('Run under the documented macOS sandbox profile')
    import socket
    import tempfile
    with socket.socket() as sock:
        with pytest.raises(PermissionError):
            sock.bind(('127.0.0.1', 0))
    # Repository is under the denied home directory. No user settings are probed.
    with pytest.raises(PermissionError):
        with tempfile.NamedTemporaryFile(dir=ROOT, prefix='.isolation-probe-'):
            pass
