"""Recovery preview after Tracker sleeps while two no-hardware printers finish."""
from pathlib import Path
import sys,tempfile,shutil,json,time
ROOT=Path(__file__).resolve().parents[3];sys.path[:0]=[str(ROOT/'src'),str(ROOT),str(ROOT/'dev/labs/uid_multi_bench')]
import run as multi
from tracker_uid_session import Session
from tracker_uid_collectors import create_workers


def main():
    out=ROOT/'output/history-recovery';out.mkdir(parents=True,exist_ok=True)
    multi.ROOT=Path(tempfile.mkdtemp(prefix='uid-recovery-',dir='/private/tmp'))
    printers=[];session=None;checks=[]
    def check(name,ok):assert ok,name;checks.append(name);print('PASS '+name,flush=True)
    def event(p,action,**kw):return p.http('/printer/bench_motion/event',dict(action=action,**kw))
    try:
        for pid,port in [('a',18791),('b',18792)]:
            p=multi.Printer(pid,port);printers.append(p)
            shutil.copy2(ROOT/'dev/labs/uid_runtime_live_bench/bench_motion.py',p.root/'klipper/klippy/extras/bench_motion.py')
            with (p.data/'config/printer.cfg').open('a') as f:f.write('\n[bench_motion]\n')
            (p.data/'gcodes/recovery.gcode').write_text('; generated by OrcaSlicer 2.3.0\n; filament used [g] = 1,0,0,0\n; filament_density = 1.24\n; filament_diameter = 1.75\n; filament_type = PLA\nM83\nSET_PRINT_STATS_INFO CURRENT_LAYER=1\nG1 E100\n')
            p.start();multi.wait(lambda:p.http('/printer/info')['result']['state']=='ready')
            p.http('/server/files/metascan',{'filename':'recovery.gcode'})
        directory=multi.ROOT/'app';allowed=[p.url for p in printers]
        session=Session(directory,allowed_urls=allowed,worker_factory=create_workers)
        settings=session.call('settings');session.call('save_settings',values=dict(printers=[dict(id=p.pid,name=p.pid,url=p.url) for p in printers]),expected_revision=settings['revision'])
        session.call('connect_printers',confirmed=True)
        multi.wait(lambda:all(v['state']=='ready' for v in session.fleet.snapshot().values()))
        for p in printers:
            session.call('create_spool','Spool '+p.pid,500,details={'material':'PLA'},assignment=dict(printer_id=p.pid,channel='0',expected_version='',confirmed=True))
            multi.wait(lambda:all(p.http('/printer/objects/query?bench_motion')['result']['status']['bench_motion']['subscribers']))
            event(p,'start',filename='recovery.gcode')
        multi.wait(lambda:len(session.call('inspect')['jobs'])==2)
        time.sleep(3) # allow verified plan + history association to persist
        keys={j['printer_id']:j['job_key'] for j in session.call('inspect')['jobs']}
        session.close();session=None
        for p in printers:event(p,'motion',head=0,length=100,stamp=1)
        event(printers[0],'complete');event(printers[1],'cancel')
        time.sleep(1)
        session=Session(directory,allowed_urls=allowed,worker_factory=create_workers)
        session.call('connect_printers',confirmed=True)
        def preview(pid):
            try:return session.call('recovery_preview',keys[pid],layer=1 if pid=='b' else None)
            except ValueError:return None
        proposals={pid:multi.wait(lambda pid=pid:preview(pid)) for pid in keys}
        check('completed and cancelled history recover after owner restart',proposals['a']['history_status']=='completed' and proposals['b']['history_status']=='cancelled')
        check('completed counter is recovered and interrupted estimate is explicit',proposals['a']['totals_mg']=={'0':298} and (proposals['b']['totals_mg']=={'0':298} or proposals['b']['ranges_mg']=={'0':[0,298]}))
        for _ in range(3):
            for p in printers:session.call('history',p.pid,p.http('/server/history/list')['result']['jobs'])
        check('replayed previews never debit',not session.call('inspect')['debits'] and all(s['remaining_mg']==500000 for s in session.call('inspect')['spools']))
        check('Spoolman remains empty',not session.call('library_snapshot')['remote_outbox'])
        (out/'results.json').write_text(json.dumps(dict(checks=checks,proposals=proposals,root=str(multi.ROOT)),indent=2))
    finally:
        if session:session.close()
        for p in printers:
            p.stop_m();p.stop_k();cfg=p.data/'config/printer.cfg';cfg.write_text(cfg.read_text().replace('\n[bench_motion]\n',''));p.close()
    (out/'cleanup.json').write_text(json.dumps(dict(stopped=all(p.k is None and p.m is None for p in printers))))
if __name__=='__main__':main()
