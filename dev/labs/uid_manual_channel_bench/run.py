"""Mixed stock/UID Klipper+Moonraker processes; temporary data and loopback only.

--bundle runs the supplied ordinary macOS application with a temporary profile.
Without it the exact same HTTP scenarios run against a source Session.
"""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import threading
import time
from urllib.request import Request, urlopen
from urllib.error import HTTPError

ROOT=Path(__file__).resolve().parents[3]
sys.path[:0]=[str(ROOT/'src'),str(ROOT/'dev/labs/uid_multi_bench')]
import run as multi
from tracker_uid_session import Session
from tracker_uid_collectors import create_workers,ReadOnlyMoonraker
from tracker_uid_gui import serve
from playwright.sync_api import sync_playwright


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bundle',type=Path)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args();out=args.output.resolve();out.mkdir(parents=True,exist_ok=True)
    multi.ROOT=Path(tempfile.mkdtemp(prefix='manual-uid-process-',dir='/private/tmp'))
    data=multi.ROOT/'app';printers=[];app=server=thread=child=None;checks=[];descriptor={}
    log=(out/'app.log').open('w')
    def check(name,condition=True):
        assert condition,name
        checks.append(name);print('PASS '+name,flush=True)
    def api(route,body=None):
        req=Request(f'http://127.0.0.1:{descriptor["port"]}/api/'+route,
                    data=None if body is None else json.dumps(body).encode(),
                    headers={'X-Tracker-Token':descriptor['token'],'Content-Type':'application/json'})
        with urlopen(req,timeout=15) as response:return json.load(response)
    def launch():
        nonlocal app,server,thread,child,descriptor
        if args.bundle:
            exe=args.bundle.resolve()/'Contents/MacOS/Snapmaker-Tracker-2.0-Candidate'
            child=subprocess.Popen([str(exe)],env=dict(os.environ,TRACKER20_DATA_DIR=str(data)),stdout=log,stderr=log)
            multi.wait(lambda:(data/'instance.json').exists())
            descriptor=json.loads((data/'instance.json').read_text())
        else:
            app=Session(data,worker_factory=create_workers,allowed_urls=[p.url for p in printers])
            server=serve(app,app.fleet,status_reader=lambda pid:ReadOnlyMoonraker(next(p.url for p in printers if p.pid==pid)).status()['print_stats']['state'])
            thread=threading.Thread(target=server.serve_forever);thread.start()
            descriptor=dict(port=server.server_port,token=server.tracker_token)
    def close():
        nonlocal app,server,thread,child
        if child and child.poll() is None:child.terminate();child.wait(20)
        child=None
        if server:server.shutdown();thread.join();server.server_close();server=None
        if app:app.close();app=None
    def state():return api('state')
    def connected():
        p={p['id']:p for p in state()['printers']}
        return len(p)==2 and p['a']['uid_state']=='module_missing' and p['b']['uid_ready']
    def event(p,action,**values):return p.http('/printer/bench_motion/event',dict(action=action,**values))
    def assign(sid):
        current=next(m for m in state()['manual_assignments'] if m['spool_id']==sid)
        return api('assign',dict(printer_id='a',channel='3',spool_id=sid,expected_version=current['version'],confirmed=True))
    result=dict(success=False,root=str(multi.ROOT),checks=checks,bundle=str(args.bundle) if args.bundle else None)
    try:
        for pid,port in [('a',18791),('b',18792)]:
            p=multi.Printer(pid,port);printers.append(p)
            if pid=='a':p.installer.rollback()  # No tracker_uid object at all.
            for source in ('dev/labs/uid_runtime_live_bench/bench_motion.py','dev/labs/uid_autorefill_boundary_bench/bench_transition.py','dev/labs/uid_autorefill_boundary_bench/barrier_protocol.py'):
                shutil.copy2(ROOT/source,p.root/'klipper/klippy/extras'/Path(source).name)
            with (p.data/'config/printer.cfg').open('a') as f:f.write('\n[bench_transition]\n')
            for name in ('first.gcode','sleep.gcode'):
                (p.data/'gcodes'/name).write_text('; generated by OrcaSlicer 2.3.0\n; filament used [g] = 0,0,0,5\n; filament_density = 1.24,1.24,1.24,1.24\n; filament_diameter = 1.75,1.75,1.75,1.75\n; filament_type = PLA;PLA;PLA;PLA\nG1 X1\n')
            p.start();multi.wait(lambda p=p:p.http('/printer/info')['result']['state']=='ready')
            for name in ('first.gcode','sleep.gcode'):p.http('/server/files/metascan',{'filename':name})
            event(p,'auto_mode',enabled=0)
        a,b=printers
        check('stock process has no tracker_uid object','tracker_uid' not in a.http('/printer/objects/list')['result']['objects'])
        launch()
        api('settings',dict(values={'language':'ru','printers':[dict(id=p.pid,name='Process '+p.pid,url=p.url) for p in printers]},expected_revision=state()['settings']['revision']))
        api('connections_start',{'confirmed':True});multi.wait(connected)
        sid=api('create',dict(name='Manual stock',remaining_g=100,details={'material':'PLA'}))['spool_id']
        b.scan(3,'04AABBCC');multi.wait(lambda:len(state()['occupied'])==1)
        with sync_playwright() as pw:
            browser=pw.chromium.launch();page=browser.new_page(viewport=dict(width=1200,height=900));errors=[]
            page.on('pageerror',lambda e:errors.append(str(e)))
            page.goto(f'http://127.0.0.1:{descriptor["port"]}/desktop')
            page.locator('#nav-spools').click();page.locator('[data-inventory-tab=slots]').click()
            page.locator('[name=slot_4]').select_option(sid)
            with page.expect_response('**/api/desktop/slots') as response:
                page.locator('#t-save-slots').click();page.locator('#graphite-confirm-apply').click()
            assert response.value.ok
            check('full-shell manual confirmation without UID changes no balance',not state()['debits'] and state()['spools'][0]['remaining_mg']==100000)
            page.locator('#desktop-tags-open').click();page.locator('#desktop-uid-status').wait_for()
            def language(lang):
                page.locator('#desktop-tags-close').click()
                page.locator('#desktop-tags-dialog').wait_for(state='hidden')
                page.locator('#lang-picker').click()
                page.locator(f'#graphite-language-dialog input[value={lang}]').check()
                page.locator('#graphite-language-save').click()
                page.wait_for_function('(l)=>currentLang===l',arg=lang)
                page.locator('#desktop-tags-open').click()
            for lang,word in [('ru','модуль не установлен'),('en','module not installed'),('de','Modul nicht installiert'),('uk','модуль не встановлено'),('es','módulo no instalado')]:
                language(lang)
                page.wait_for_function('(s)=>document.getElementById("desktop-uid-status").textContent.includes(s)',arg=word)
            page.screenshot(path=str(out/'stock-channel.png'),full_page=True)
            language('ru')
            page.locator('[data-uid="04AABBCC"]').click();page.locator('#desktop-tag-name').fill('RFID process B');page.locator('#desktop-tag-material').fill('PLA');page.locator('#desktop-tag-mass').fill('100')
            page.locator('#desktop-tag-next').click();page.locator('#desktop-tag-ack').check()
            with page.expect_response('**/api/tag_register') as response:page.locator('#desktop-tag-save').click()
            assert response.value.ok
            page.locator('[data-uid="04AABBCC"]').wait_for(state='detached')
            check('UID registration and five channel-status languages work in full shell',len(state()['spools'])==2 and not errors)
            page.screenshot(path=str(out/'registered.png'),full_page=True);browser.close()
        for p in printers:multi.wait(lambda p=p:all(p.http('/printer/objects/query?bench_transition')['result']['status']['bench_transition']['subscribers']))
        for p in printers:event(p,'start',filename='first.gcode')
        multi.wait(lambda:len(state()['recovery_plans'])==2)
        for p in printers:
            event(p,'motion',head=3,length=100,stamp=1);event(p,'motion',head=3,length=900,stamp=10);event(p,'complete')
        multi.wait(lambda:len(state()['debits'])==2)
        check('manual and RFID process collectors each debit exactly once',all(d['delta_mg']==2983 for d in state()['debits']))
        b.scan(3,'04AABBCC');time.sleep(2)
        check('repeat UID scan and history preserve both balances',len(state()['spools'])==2 and len(state()['debits'])==2)
        event(a,'start',filename='sleep.gcode');multi.wait(lambda:len(state()['recovery_plans'])==3)
        api('connections_stop',{'confirmed':True});event(a,'complete')
        api('connections_start',{'confirmed':True});multi.wait(connected);time.sleep(3)
        check('sleep completion retains saved plan without guessing manual spool usage',len(state()['debits'])==2)
        job=next(j for j in state()['jobs'] if j['printer_id']=='a' and j['state']=='active')
        detail=api('history_detail',{'job_key':job['job_key']})
        check('interrupted manual job retains original offline-viewable plan',detail['plan'][0]['planned_mg']==5000)
        request=dict(job_key=job['job_key'],action='account',expected_revision=detail['revision'],request_id='manual-process-once',confirmed=True,completed=True,allocations_mg={sid:1200},note='Synthetic reviewed consumption')
        api('history_decide',request);assert api('history_decide',request)['status']=='duplicate'
        check('edited manual usage after sleep is applied once',len(state()['debits'])==3 and next(s for s in state()['spools'] if s['spool_id']==sid)['remaining_mg']==95817)
        assign(sid);baseline=state()['debits']
        for src,ch,dst,target in [('a','3','b','1'),('b','1','a','3')]:
            current=next(m for m in state()['manual_assignments'] if m['spool_id']==sid)
            req=dict(spool_id=sid,source_printer=src,source_channel=ch,target_printer=dst,target_channel=target,expected_version=current['version'],request_id='transfer-'+src,confirmed=True)
            assert api('transfer',req)==api('transfer',req)
        check('manual transfer between stock and UID printers changes no usage',state()['debits']==baseline)
        a.stop_m();multi.wait(lambda:not next(p for p in state()['printers'] if p['id']=='a')['ready'])
        check('stock disconnect does not stop other RFID printer',next(p for p in state()['printers'] if p['id']=='b')['uid_ready'])
        a.start_m();multi.wait(connected)
        check('reconnect requires manual confirmation again',not next(m for m in state()['manual_assignments'] if m['spool_id']==sid)['confirmed'])
        assign(sid);check('reconfirmation never debits',state()['debits']==baseline)
        api('connections_stop',{'confirmed':True});package=api('backup_package',{})
        preview=api('validate_backup',{'package':package});api('restore_backup',dict(package=package,expected_revision=preview['current_revision'],confirmed=True))
        close();launch()
        check('ordinary restart preserves settings and ledger with connections off',not state()['connections']['connected'] and len(state()['settings']['values']['printers'])==2 and state()['debits']==baseline)
        api('connections_start',{'confirmed':True});multi.wait(connected);time.sleep(3)
        check('restore restart and repeated live history cannot double debit',state()['debits']==baseline and not state()['delivery'])
        result.update(success=True,state=state())
    finally:
        close();log.close()
        for p in printers:
            p.stop_m();p.stop_k()
            cfg=p.data/'config/printer.cfg';cfg.write_text(cfg.read_text().replace('\n[bench_transition]\n',''));p.close()
            for name in ('klippy','moonraker'):shutil.copy2(p.data/f'logs/{name}.log',out/f'{p.pid}-{name}.log')
        result['processes_stopped']=all(p.k is None and p.m is None for p in printers)
        (out/'results.json').write_text(json.dumps(result,indent=2))
    print(f'{len(checks)} checks passed; processes stopped',flush=True)


if __name__=='__main__':main()
