"""Synthetic producer; writes ONLY an explicitly marked observer lab."""
from pathlib import Path
import argparse


def payload(weights='10, 20, 0, 0'):
    return ('; generated by Snapmaker Orca synthetic fixture\n'
            '; EXECUTABLE_BLOCK_START\nG1 X1\n; EXECUTABLE_BLOCK_END\n'
            '; filament used [g] = ' + weights + '\n'
            '; CONFIG_BLOCK_START\n; printer_model = Snapmaker U1\n'
            '; CONFIG_BLOCK_END\n\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('root', type=Path)
    parser.add_argument('action', choices=['partial', 'complete', 'reslice', 'plates'])
    args = parser.parse_args()
    root = args.root.resolve(strict=True)
    if (root / 'OBSERVER_LAB_ONLY').read_text() != 'synthetic-only\n':
        raise SystemExit('Not an observer lab')
    folder = root / 'slices' / 'Nov_04' / 'demo#99999#1' / 'Metadata'
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / '.99999.1.gcode'
    temporary = Path(str(target) + '.tmp')
    if args.action == 'partial':
        temporary.write_bytes(payload()[:-30])
    elif args.action in ('complete', 'reslice'):
        temporary.write_bytes(payload('120, 20, 0, 0' if args.action == 'reslice' else '10, 20, 0, 0'))
        temporary.replace(target)
    else:
        for index in (2, 3):
            target = folder / ('.99999.%d.gcode' % index)
            temporary = Path(str(target) + '.tmp')
            temporary.write_bytes(payload('5, 0, 30, 0'))
            temporary.replace(target)


if __name__ == '__main__':
    main()
