"""Ordinary launcher subprocess + its GUI API + two real no-hardware servers."""
from pathlib import Path
import sys,json,tempfile,shutil,time,re,urllib.request,subprocess,signal
ROOT=Path(__file__).resolve().parents[3];sys.path[:0]=[str(ROOT/'src'),str(ROOT),str(ROOT/'dev/labs/uid_multi_bench')]
import run as multi
from tracker_uid_session import Session


def main():
    out=ROOT/'output/launcher-live';out.mkdir(parents=True,exist_ok=True)
    multi.ROOT=Path(tempfile.mkdtemp(prefix='uid-launcher-live-',dir='/private/tmp'))
    printers=[];app=None;checks=[];token=None
    def check(name,ok):assert ok,name;checks.append(name);print('PASS '+name,flush=True)
    def api(route,data=None):
        request=urllib.request.Request('http://127.0.0.1:18773/api/'+route,data=json.dumps(data).encode() if data is not None else None,headers={'Content-Type':'application/json','X-Tracker-Token':token})
        with urllib.request.urlopen(request,timeout=15) as response:return json.load(response)
    def launch():
        nonlocal token
        log=(out/'launcher.log').open('ab')
        proc=subprocess.Popen([sys.executable,str(ROOT/'dev/labs/uid_settings_bench/run.py'),'--data',str(multi.ROOT/'app'),'--port','18773','--allow-url',printers[0].url,'--allow-url',printers[1].url],cwd=ROOT,stdout=log,stderr=log);log.close()
        def ready():
            with urllib.request.urlopen('http://127.0.0.1:18773',timeout=2) as r:return r.read().decode()
        html=multi.wait(ready);token=json.loads(re.search(r'const TOKEN=("[^"]+");',html).group(1));return proc
    try:
        for pid,port in [('a',18771),('b',18772)]:
            p=multi.Printer(pid,port);printers.append(p)
            shutil.copy2(ROOT/'dev/labs/uid_runtime_live_bench/bench_motion.py',p.root/'klipper/klippy/extras/bench_motion.py')
            with (p.data/'config/printer.cfg').open('a') as f:f.write('\n[bench_motion]\n')
            for kind in ['first','second']:
                (p.data/f'gcodes/{kind}-{pid}.gcode').write_text('; generated by OrcaSlicer 2.3.0\n; filament used [g] = 1,1,1,1\n; filament_density = 1.24,1.24,1.24,1.24\n; filament_diameter = 1.75,1.75,1.75,1.75\n; filament_type = PLA;PLA;PLA;PLA\nG1 X1\n')
            p.start();multi.wait(lambda p=p:p.http('/printer/info')['result']['state']=='ready')
            for kind in ['first','second']:
                p.http('/server/files/metascan',{'filename':f'{kind}-{pid}.gcode'})
        # Register known physical tags in an empty synthetic catalog before launch.
        seed=Session(multi.ROOT/'app')
        seed.call('register','04112233','RFID A',500000);seed.call('register','04AABBCCDDEEFF','RFID B',300000);seed.close()
        app=launch();initial=api('state')
        api('settings',{'values':{'printers':[dict(id=p.pid,name='Printer '+p.pid.upper(),url=p.url) for p in printers]},'expected_revision':initial['settings']['revision']})
        api('connections_start',{'confirmed':True})
        multi.wait(lambda:all(p['ready'] for p in api('state')['printers']))
        a,b=printers;a.scan(0,'04112233');b.scan(1,'04AABBCCDDEEFF')
        def recognized():return [r for r in api('state')['occupied'] if r['state']=='recognized']
        multi.wait(lambda:len(recognized())==2)
        check('launcher reads 4-byte and 7-byte RFID through two real readers',set(r['uid'] for r in recognized())=={'04112233','04AABBCCDDEEFF'})
        def subscribed(p):return all(p.http('/printer/objects/query?bench_motion')['result']['status']['bench_motion']['subscribers'])
        for p in printers:multi.wait(lambda p=p:subscribed(p))
        check('same launcher enables UID motion and history from saved settings',api('state')['connections']['collectors_enabled'])
        if '--browser' in sys.argv:
            (out/'go').unlink(missing_ok=True)
            (out/'ready').write_text(str(multi.ROOT));multi.wait(lambda:(out/'go').exists(),timeout=180)
            multi.wait(lambda:len(recognized())==2)
            for p in printers:multi.wait(lambda p=p:subscribed(p))
        def event(p,action,**kw):p.http('/printer/bench_motion/event',dict(action=action,**kw))
        for p in printers:event(p,'start',filename='first-'+p.pid+'.gcode')
        multi.wait(lambda:len(api('state')['jobs'])==2)
        # A verified profile comes from the served G-code, never injected into the collector.
        def verified(pid):
            logs=multi.ROOT/f'app/motion-{pid}/motion-diagnostic.jsonl'
            return logs.exists() and 'motion_summary' in logs.read_text()
        time.sleep(2)
        for p,h in zip(printers,[0,1]):event(p,'motion',head=h,length=100,stamp=1)
        time.sleep(.7)
        for p in printers:event(p,'complete')
        multi.wait(lambda:len(api('state')['debits'])==2,timeout=45)
        check('verified remote G-code and RFID debit correct spools once',sorted(s['remaining_mg'] for s in api('state')['spools'])==[299702,499702])
        time.sleep(2);check('automatic repeated history does not duplicate debit',len(api('state')['debits'])==2)
        # Moving a physical tag keeps one spool ID and its balance.
        sid=next(s['spool_id'] for s in api('state')['spools'] if s['uid']=='04112233')
        a.clear(0);b.scan(2,'04112233')
        multi.wait(lambda:any(r['printer_id']=='b' and r['channel']=='2' and r['state']=='recognized' for r in api('state')['occupied']))
        check('RFID transfer keeps spool ID and balance',any(r['spool']['spool_id']==sid and r['spool']['remaining_mg']==499702 for r in recognized() if r['channel']=='2'))
        a.scan(3,'04112233')
        multi.wait(lambda:len([r for r in api('state')['occupied'] if r['state']=='conflict'])==2)
        check('duplicate UID blocks both locations',all(not r['usable'] for r in api('state')['occupied'] if r['uid']=='04112233'))
        a.clear(3);b.clear(2);a.scan(0,'04112233');multi.wait(lambda:len(recognized())==2)
        a.scan(3,'04AABBCCDDEEFF112233')
        multi.wait(lambda:any(r['uid']=='04AABBCCDDEEFF112233' and r['state']=='needs_registration' for r in api('state')['occupied']))
        check('new 10-byte tag is read without inventing spool or balance',len(api('state')['spools'])==2)
        a.clear(3)
        for p in printers:event(p,'start',filename='second-'+p.pid+'.gcode')
        multi.wait(lambda:len(api('state')['jobs'])==4);time.sleep(2)
        for p,h in zip(printers,[0,1]):event(p,'motion',head=h,length=100,stamp=10)
        a.stop_m();multi.wait(lambda:not next(p for p in api('state')['printers'] if p['id']=='a')['ready'])
        check('disconnect invalidates RFID confirmation',all(not r['confirmed'] for r in api('state')['occupied'] if r['printer_id']=='a'))
        event(b,'complete');multi.wait(lambda:len(api('state')['debits'])==3,timeout=45)
        check('second printer accounts while first is disconnected',True)
        a.start_m();multi.wait(lambda:all(p['ready'] for p in api('state')['printers']))
        a.scan(0,'04112233');multi.wait(lambda:len(recognized())==2);multi.wait(lambda:subscribed(a));event(a,'cancel')
        time.sleep(2)
        check('RFID rescan does not repair interrupted motion evidence',len(api('state')['debits'])==3 and any(not j['mapping_valid'] for j in api('state')['jobs'] if j['printer_id']=='a'))
        api('connections_stop',{'confirmed':True});app.send_signal(signal.SIGINT);assert app.wait(15)==0;app=None
        app=launch();state=api('state')
        check('restart preserves settings UID identities and ledger',len(state['settings']['values']['printers'])==2 and len(state['debits'])==3 and not state['connections']['connected'])
        api('connections_start',{'confirmed':True});multi.wait(lambda:all(p['ready'] for p in api('state')['printers']));time.sleep(2)
        final=api('state');check('restarted collectors replay history without double debit',len(final['debits'])==3)
        (out/'results.json').write_text(json.dumps(dict(checks=checks,state=final,root=str(multi.ROOT)),indent=2))
    finally:
        if app and app.poll() is None:
            app.send_signal(signal.SIGINT)
            try:app.wait(15)
            except subprocess.TimeoutExpired:app.kill();app.wait();raise
        for p in printers:
            p.stop_m();p.stop_k();cfg=p.data/'config/printer.cfg';cfg.write_text(cfg.read_text().replace('\n[bench_motion]\n',''));p.close()
            for name in ['klippy','moonraker']:shutil.copy2(p.data/f'logs/{name}.log',out/f'{p.pid}-{name}.log')
        if (multi.ROOT/'app').exists():shutil.copytree(multi.ROOT/'app',out/'app',dirs_exist_ok=True)
    print(f'{len(checks)} launcher checks passed; all processes stopped',flush=True)

if __name__=='__main__':main()
