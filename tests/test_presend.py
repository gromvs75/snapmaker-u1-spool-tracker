@pytest.fixture
def request_data(tmp_path):
    gcode = tmp_path / 'cube.gcode'
    gcode.write_text('; generated by Snapmaker Orca 2.4.1\n'
                     '; filament_type = PLA;PLA;PLA;PLA\n'
                     '; filament used [g] = 10, 20, 0, 0\nT0\nG1 X1\n')
    db = {'slots': {'1': 's1', '2': 's2', '3': '', '4': ''},
          'spools': {'s1': {'name': 'A', 'material': 'PLA', 'remaining_g': 100},
                     's2': {'name': 'B', 'material': 'PLA', 'remaining_g': 100}},
          'safety_margin_g': 5}
    inventory = tmp_path / 'inventory.json'
    inventory.write_text(json.dumps(db))
    return {'version': 1, 'request_id': 'test-1', 'context_id': 'plate-1',
            'device_id': 'FAKE-U1', 'action': 'send', 'mapping': [0, 1, 2, 3],
            'gcode_path': str(gcode), 'inventory_path': str(inventory),
            'sha256': digest(gcode.read_bytes())}


def rewrite_db(request, change):
    path = Path(request['inventory_path'])
    db = json.loads(path.read_text())
    change(db)
    path.write_text(json.dumps(db))


def rewrite_gcode(request, change):
    path = Path(request['gcode_path'])
    path.write_text(change(path.read_text()))
    request['sha256'] = digest(path.read_bytes())


def assert_blocked(adapter, result):
    assert result['decision'] == 'blocked', result
    assert adapter.transport.uploads == []
    assert adapter.transport.starts == []


@pytest.mark.parametrize('action', ['send', 'print'])
def test_allow_and_single_attempt(request_data, action):
    request_data['action'] = action
    before = Path(request_data['inventory_path']).read_bytes()
    adapter = TestAdapter()
    assert adapter.execute(request_data)['decision'] == 'allowed'
    assert adapter.transport.uploads == [{'sha256': request_data['sha256'], 'device_id': 'FAKE-U1'}]
    assert adapter.transport.starts == (['FAKE-U1'] if action == 'print' else [])
    assert adapter.execute(request_data)['decision'] == 'blocked'
    assert len(adapter.transport.uploads) == 1
    assert Path(request_data['inventory_path']).read_bytes() == before


@pytest.mark.parametrize('action', ['send', 'print'])
@pytest.mark.parametrize('fault', ['shortage', 'unassigned', 'mismatch', 'unknown', 'invalid_inventory',
                                   'bad_hash', 'mapping', 'extra_channel', 'missing_file', 'duplicate_metadata'])
def test_policy_and_input_failures_never_send(request_data, action, fault):
    request_data['action'] = action
    if fault == 'shortage':
        rewrite_db(request_data, lambda db: db['spools']['s1'].update(remaining_g=14))
    elif fault == 'unassigned':
        rewrite_db(request_data, lambda db: db['slots'].update({'1': ''}))
    elif fault in ('mismatch', 'unknown'):
        rewrite_db(request_data, lambda db: db['spools']['s1'].update(material='PETG' if fault == 'mismatch' else '?'))
    elif fault == 'invalid_inventory':
        rewrite_db(request_data, lambda db: db.update(safety_margin_g=-1))
    elif fault == 'bad_hash':
        request_data['sha256'] = '0' * 64
    elif fault == 'mapping':
        request_data['mapping'] = [True, 1, 2, 3]
    elif fault == 'extra_channel':
        request_data['mapping'].append(0)
    elif fault == 'missing_file':
        Path(request_data['gcode_path']).unlink()
    elif fault == 'duplicate_metadata':
        rewrite_gcode(request_data, lambda s: s + '; filament used [g] = 1, 0, 0, 0\n')
    adapter = TestAdapter()
    assert_blocked(adapter, adapter.execute(request_data))


