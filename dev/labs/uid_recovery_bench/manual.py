"""Two real no-hardware process printers: automatic vs manual replacement."""
from pathlib import Path
import sys,tempfile,shutil,json,time
ROOT=Path(__file__).resolve().parents[3];sys.path[:0]=[str(ROOT/'src'),str(ROOT),str(ROOT/'dev/labs/uid_multi_bench')]
import run as multi
from tracker_uid_session import Session
from tracker_uid_collectors import create_workers


def main():
    out=ROOT/'output/manual-uid-replacement';out.mkdir(parents=True,exist_ok=True)
    multi.ROOT=Path(tempfile.mkdtemp(prefix='uid-calc-',dir='/private/tmp'));printers=[];session=None;checks=[]
    def check(name,ok):assert ok,name;checks.append(name);print('PASS '+name,flush=True)
    def event(p,action,**kw):return p.http('/printer/bench_motion/event',dict(action=action,**kw))
    try:
        for pid,port in [('a',18791),('b',18792)]:
            p=multi.Printer(pid,port);printers.append(p)
            for file in [ROOT/'dev/labs/uid_runtime_live_bench/bench_motion.py',ROOT/'dev/labs/uid_autorefill_boundary_bench/bench_transition.py',ROOT/'dev/labs/uid_autorefill_boundary_bench/barrier_protocol.py']:
                shutil.copy2(file,p.root/'klipper/klippy/extras'/file.name)
            with (p.data/'config/printer.cfg').open('a') as f:f.write('\n[bench_transition]\n')
            (p.data/'gcodes/recovery.gcode').write_text('; generated by OrcaSlicer 2.3.0\n; filament used [g] = 0,0,0,70\n; filament_density = 1.24,1.24,1.24,1.24\n; filament_diameter = 1.75,1.75,1.75,1.75\n; filament_type = PLA;PLA;PLA;PLA\nG1 X1\n')
            p.start();multi.wait(lambda:p.http('/printer/info')['result']['state']=='ready')
            p.http('/server/files/metascan',{'filename':'recovery.gcode'})
            event(p,'auto_mode',enabled=0)
        directory=multi.ROOT/'app';allowed=[p.url for p in printers]
        session=Session(directory,allowed_urls=allowed,worker_factory=create_workers)
        for uid,balance in [('04112233',20000),('04AABBCC',300000),('04112244',20000),('04AABBDD',300000),('04CCCCDD',100000),('04EEEEFF',100000)]:session.call('register',uid,uid,balance)
        settings=session.call('settings');session.call('save_settings',values=dict(printers=[dict(id=p.pid,name=p.pid,url=p.url) for p in printers]),expected_revision=settings['revision'])
        session.call('connect_printers',confirmed=True)
        multi.wait(lambda:all(v['state']=='ready' for v in session.fleet.snapshot().values()))
        for p,uids in zip(printers,[['04112233','04AABBCC'],['04112244','04AABBDD']]):
            p.scan(3,uids[0]);p.scan(1,uids[1])
        multi.wait(lambda:len([r for r in session.call('refresh') if r['usable']])==4)
        for p in printers:
            multi.wait(lambda:all(p.http('/printer/objects/query?bench_transition')['result']['status']['bench_transition']['subscribers']))
            event(p,'start',filename='recovery.gcode')
        multi.wait(lambda:len(session.call('inspect')['recovery_plans'])==2)
        check('manual mode saved for both printers',all(p['auto_replenish'] is False for p in session.call('inspect')['recovery_plans']))
        for p in printers:
            event(p,'motion',head=3,length=100,stamp=1);event(p,'pause')
        time.sleep(2)
        printers[0].scan(3,'04CCCCDD')
        multi.wait(lambda:any(json.loads(e['payload'])['proven'] for e in session.call('inspect')['replacement_events']))
        check('paused change journal preserves old and new UID',len(session.call('inspect')['replacement_events'])==1)
        session.close();session=None
        # B changes while Tracker sleeps: no observed boundary -> review only.
        printers[1].scan(3,'04EEEEFF')
        for p in printers:
            event(p,'resume');event(p,'motion',head=3,length=900,stamp=10);event(p,'complete')
        time.sleep(1)
        session=Session(directory,allowed_urls=allowed,worker_factory=create_workers);session.call('connect_printers',confirmed=True)
        multi.wait(lambda:len(session.call('inspect')['debits'])==2,timeout=40)
        def balances():return {s['uid']:s['remaining_mg'] for s in session.call('inspect')['spools']}
        check('sleep after observed replacement preserves partial old balance',balances()['04112233']==19702 and balances()['04CCCCDD']==97315)
        multi.wait(lambda:len(session.call('inspect')['replacement_events'])==2,timeout=20)
        check('change during sleep is journalled unproven and never debited',balances()['04112244']==20000 and balances()['04EEEEFF']==100000 and sum(json.loads(e['payload'])['proven'] for e in session.call('inspect')['replacement_events'])==1)
        time.sleep(2)
        check('history replay does not duplicate journal or ledger',len(session.call('inspect')['replacement_events'])==2 and len(session.call('inspect')['debits'])==2)
        session.close();session=None
        session=Session(directory,allowed_urls=allowed,worker_factory=create_workers);session.call('connect_printers',confirmed=True);time.sleep(6)
        check('second restart preserves exact same debits',len(session.call('inspect')['debits'])==2 and balances()['04CCCCDD']==97315)
        (out/'results.json').write_text(json.dumps(dict(checks=checks,state=session.call('inspect'),root=str(multi.ROOT)),indent=2))
    finally:
        if session:session.close()
        for p in printers:
            p.stop_m();p.stop_k();cfg=p.data/'config/printer.cfg';cfg.write_text(cfg.read_text().replace('\n[bench_transition]\n',''));p.close()
    (out/'cleanup.json').write_text(json.dumps(dict(stopped=all(p.k is None and p.m is None for p in printers))))
if __name__=='__main__':main()
